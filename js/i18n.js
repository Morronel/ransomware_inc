RI.L = function (obj) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  return obj[RI.lang] != null ? obj[RI.lang] : obj.en;
};

// Faction-specific string if one exists (key_factionId), otherwise the shared one.
RI.tf = function (fid, key, params) {
  var k = key + '_' + fid;
  return RI.STR.en[k] != null ? RI.t(k, params) : RI.t(key, params);
};

RI.t = function (key, params) {
  var s = (RI.STR[RI.lang] && RI.STR[RI.lang][key]);
  if (s == null) s = RI.STR.en[key];
  if (s == null) return key;
  if (params && typeof s === 'string') {
    s = s.replace(/\{(\w+)\}/g, function (m, k) { return params[k] != null ? params[k] : m; });
  }
  return s;
};

RI.fmt = function (s, params) {
  return String(s).replace(/\{(\w+)\}/g, function (m, k) { return params[k] != null ? params[k] : m; });
};
